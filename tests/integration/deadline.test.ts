import { env } from 'cloudflare:workers';
import { expect, it } from 'vitest';
import localWorker from '../../src/worker/local';
const encode = (value: unknown) => btoa(JSON.stringify(value)).replace(/=/g, '');
const now = Math.floor(Date.now()/1000);
const token = `${encode({alg:'none'})}.${encode({sub:'a',aud:'demo-shared-task-board',iss:'https://securetoken.google.com/demo-shared-task-board',iat:now,auth_time:now,exp:now+3600})}.`;
const local = { ...env, AUTH_MODE:'emulator' as const, ENVIRONMENT:'local', FIREBASE_PROJECT_ID:'demo-shared-task-board' };
const call = (path:string, method:string, body:unknown) => localWorker.fetch(new Request(`https://example.test${path}`, { method, headers:{Authorization:`Bearer ${token}`, 'Content-Type':'application/json'}, body:JSON.stringify(body) }), local);
it('supports omitted, canonicalized, changed and cleared deadlines without altering status', async () => {
  await env.DB.prepare("INSERT INTO partners VALUES (1,'a','Ana',1),(2,'b','Bea',1)").run();
  const create = await call('/api/tasks','POST',{title:'Tarea',assigneeUid:'a'});
  const first = await create.json() as { task:{ id:string; deadline:string|null; status:string }; revision:number };
  expect(first.task.deadline).toBeNull();
  const explicitNull = await call('/api/tasks','POST',{ title:'Sin fecha', assigneeUid:'a', deadline:null });
  expect(((await explicitNull.json()) as typeof first).task.deadline).toBeNull();
  const withDeadline = await call('/api/tasks','POST',{ title:'Con fecha', assigneeUid:'b', deadline:'2020-01-01T00:00:00Z' });
  expect(((await withDeadline.json()) as typeof first).task.deadline).toBe('2020-01-01T00:00:00Z');
  const path = `/api/tasks/${first.task.id}`;
  const edit = (deadline:string|null) => ({title:'Tarea',assigneeUid:'a',status:'blocked',deadline});
  const changed = await call(path,'PUT',edit('2026-11-02T09:00:00-06:00'));
  const updated = await changed.json() as typeof first;
  expect(updated.task.deadline).toBe('2026-11-02T15:00:00Z');
  expect(updated.task.status).toBe('blocked');
  const changedAgain = await call(path,'PUT',edit('2027-01-01T09:00:00Z'));
  expect(((await changedAgain.json()) as typeof first).task.deadline).toBe('2027-01-01T09:00:00Z');
  const rejected = await call(path,'PUT',edit('2027-02-30T12:00:00Z'));
  expect(rejected.status).toBe(400);
  const cleared = await call(path,'PUT',edit(null));
  const result = await cleared.json() as typeof first;
  expect(result.task.deadline).toBeNull();
  expect(result.task.status).toBe('blocked');
  expect(result.revision).toBe(6);
});
